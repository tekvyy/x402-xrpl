/**
 * Generate the three unfunded XRPL wallets the mainnet run needs and write them
 * to a gitignored `.env.mainnet` (mode 0600):
 *
 *   GATEWAY  — the gateway's own wallet (settles, redeems channels)
 *   AGENT    — the paying client (opens the PayChan, makes pay-per-call)
 *   SELLER   — the payout address credits are forwarded to
 *
 *   node scripts/gen-mainnet-wallets.mjs
 *
 * Keys are generated locally and never leave this machine. The accounts do not
 * exist on ledger until you fund each address with real XRP; the script prints
 * the funding target per wallet. Re-running overwrites the file, so back up
 * `.env.mainnet` once the accounts are funded.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(resolve(rootDir, 'packages/gateway/package.json'));
const { Wallet } = require('xrpl');

const OUT_PATH = resolve(rootDir, '.env.mainnet');

/**
 * Funding targets in XRP. Mainnet base reserve is 1 XRP per account and 0.2 XRP
 * per owned object (a PayChan is one owned object); the remainder is headroom
 * for fees and the amounts actually being paid.
 */
const WALLETS = [
  {
    key: 'GATEWAY',
    envVar: 'GATEWAY_XRPL_SEED_MAINNET',
    fundXrp: 3,
    purpose: 'gateway wallet — set this seed as GATEWAY_XRPL_SEED_MAINNET in Railway',
  },
  {
    key: 'AGENT',
    envVar: 'AGENT_SEED',
    fundXrp: 6,
    purpose: 'paying agent — funds the channel deposit and the pay-per-call',
  },
  {
    key: 'SELLER',
    envVar: 'SELLER_SEED',
    fundXrp: 2,
    purpose: 'seller payout address — must exist on ledger to receive',
  },
];

if (existsSync(OUT_PATH)) {
  console.error(
    `refusing to overwrite ${OUT_PATH}\n` +
      'Delete or move it first if you really want a fresh set of wallets.',
  );
  process.exit(1);
}

const generated = WALLETS.map((spec) => ({ ...spec, wallet: Wallet.generate() }));

const body = [
  '# Generated by scripts/gen-mainnet-wallets.mjs — MAINNET KEYS, REAL FUNDS.',
  '# Gitignored. Do not commit, paste, or share. Back this file up.',
  '',
  ...generated.flatMap(({ key, envVar, wallet, fundXrp }) => [
    `# ${key} — address ${wallet.classicAddress} — fund with ~${fundXrp} XRP`,
    `${key}_ADDRESS=${wallet.classicAddress}`,
    `${envVar}=${wallet.seed}`,
    '',
  ]),
].join('\n');

writeFileSync(OUT_PATH, body, { mode: 0o600 });

const totalXrp = generated.reduce((sum, w) => sum + w.fundXrp, 0);

console.log(`Wrote ${OUT_PATH} (mode 0600).\n`);
console.log('Fund these addresses with real XRP before deploying:\n');
for (const { key, wallet, fundXrp, purpose } of generated) {
  console.log(`  ${key.padEnd(8)} ${wallet.classicAddress}`);
  console.log(`  ${''.padEnd(8)} send ~${fundXrp} XRP — ${purpose}\n`);
}
console.log(`Total to fund: ~${totalXrp} XRP.`);
console.log('Seeds are in .env.mainnet. Verify funding with:');
console.log('  node scripts/check-mainnet-wallets.mjs');
